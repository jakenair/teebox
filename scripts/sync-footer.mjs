#!/usr/bin/env node
/**
 * scripts/sync-footer.mjs — stamp the ONE shared footer into every page.
 *
 *   node scripts/sync-footer.mjs            # write
 *   node scripts/sync-footer.mjs --dry-run  # report only
 *   node scripts/sync-footer.mjs --check    # exit 1 if any page is stale (CI)
 *
 * This script OWNS the canonical footer markup. For every target page it
 * replaces the region between
 *     <!-- tb-footer:start -->  …  <!-- tb-footer:end -->
 * On the first run (no markers yet) it removes the page's existing
 * <footer>…</footer> and puts the marked region in its place; pages with no
 * footer get the region just before </body>. It also makes sure
 *     <link rel="stylesheet" href="/assets/footer.css">
 * is in <head> — except offline.html, which is served by the service worker
 * with no network, so there the stylesheet is INLINED inside the region.
 *
 * Idempotent: running it twice is a no-op. It refuses to touch a page that
 * has more than one <footer> (never guess at page content).
 *
 * Per-page knobs (PAGE_CONFIG below):
 *   extras  — extra link rows (index.html carries the old Top-Brands /
 *             Company links so their SEO value is not dropped).
 *   note    — one line of context under the links (brand-page disclaimers
 *             are auto-detected from the old footer on the first run and
 *             then preserved from the existing region on later runs).
 *   shim    — a few CSS lines for the three flex-centred one-card pages
 *             (404 / offline / bingo stub) so the footer sits at the bottom
 *             instead of beside the card. Lives inside the owned region.
 *   inline  — inline footer.css instead of linking it (offline.html).
 *
 * listing/<id>/index.html pages are generated by generate-listing-pages.mjs,
 * which emits NO footer — nothing to do there (checked 2026-10-26).
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const DRY = process.argv.includes('--dry-run');
const CHECK = process.argv.includes('--check');

const START = '<!-- tb-footer:start -->';
const END = '<!-- tb-footer:end -->';
const CSS_HREF = '/assets/footer.css';
const LINK_TAG = `<link rel="stylesheet" href="${CSS_HREF}">`;

// ---------------------------------------------------------------------------
// Canonical content
// ---------------------------------------------------------------------------
const LINKS = [
  ['Marketplace', '/'],
  ['Sell', '/?sell=1'],
  ['How it works', '/about.html'],          // about.html has no section ids → page
  ['FAQ', '/support.html'],                 // support.html has no #faq anchor → page
  ['Terms', '/terms.html'],
  ['Privacy', '/privacy.html'],
  ['Refunds', '/refunds.html'],
  ['Contact', 'mailto:support@teeboxmarket.com'], // no #contact anchor on support.html
];
const APP_STORE_URL = 'https://apps.apple.com/app/id6763954448';
const INSTAGRAM_URL = 'https://instagram.com/teeboxmarket';
const LEGAL_CO = '© 2026 TEEBOX MARKET LLC';
const LEGAL_ADDR = '16649 Oak Park Ave, Ste H #1160, Tinley Park, IL 60477';

const INSTAGRAM_SVG =
  '<svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">' +
  '<rect x="3" y="3" width="18" height="18" rx="5"/>' +
  '<circle cx="12" cy="12" r="4"/>' +
  '<circle class="tbf-dot" cx="17.5" cy="6.5" r="1"/></svg>';

/** Old index.html footer columns with real hrefs (SEO value) — index only. */
const INDEX_EXTRAS = [
  {
    label: 'Brands',
    links: [
      ['Smathers &amp; Branson', '/brand/smathers-branson.html'],
      ['Peter Millar', '/brand/peter-millar.html'],
      ['Holderness &amp; Bourne', '/brand/holderness-bourne.html'],
      ['Scotty Cameron', '/brand/scotty-cameron.html'],
      ['Titleist', '/brand/titleist.html'],
      ['TaylorMade', '/brand/taylormade.html'],
    ],
  },
  {
    label: 'Explore',
    links: [
      ['About', '/about.html'],
      ['Reads', '/reads/index.html'],
      ['Evans Scholars', '/evans-scholars.html'],
    ],
  },
];

/** CSS for the flex-centred single-card pages. Kept inside the owned region. */
const SHIM_CARD_COLUMN = (pad) =>
  `body{flex-direction:column}` +
  `body>:first-child{margin-top:auto}` +
  `.tb-footer{margin:auto ${-pad} ${-pad};width:calc(100% + ${pad} * 2)}`;

const PAGE_CONFIG = {
  'index.html': { extras: INDEX_EXTRAS },
  'round.html': { note: 'Shared from a TeeBox Passport.' },
  // body { display:flex; flex-direction:column; padding:1rem } + UA 8px margin
  '404.html': { shim: 'body{margin:0}' + SHIM_CARD_COLUMN('1rem') },
  // body { display:flex (row); padding:2rem } — served offline → inline CSS
  'offline.html': { inline: true, shim: SHIM_CARD_COLUMN('2rem') },
  // redirect stub (0 s meta-refresh); body { display:flex (row); padding:0 }
  'bingo.html': { shim: SHIM_CARD_COLUMN('0px') },
};

const TARGETS = [
  'index.html', 'bingo.html', 'round.html', 'about.html', 'evans-scholars.html',
  'support.html', 'terms.html', 'privacy.html', 'refunds.html',
  'acceptable-use.html', 'dmca.html', 'unsubscribe.html', '404.html', 'offline.html',
  ...listHtml('reads'),
  ...listHtml('brand'),
];

function listHtml(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs).filter((f) => f.endsWith('.html')).sort().map((f) => `${dir}/${f}`);
}

// ---------------------------------------------------------------------------
// Markup
// ---------------------------------------------------------------------------
function escapeHtml(s) {
  return s.replace(/&(?!amp;|lt;|gt;|quot;|#\d+;)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function renderFooter({ extras = [], note = '', shim = '', inline = false }) {
  const out = [];
  out.push(START);
  if (inline) {
    const css = fs.readFileSync(path.join(ROOT, 'assets', 'footer.css'), 'utf8').trim();
    out.push(`<style id="tb-footer-css">\n${css}\n</style>`);
  }
  if (shim) out.push(`<style id="tb-footer-shim">${shim}</style>`);
  out.push('<footer class="tb-footer">');
  out.push('  <div class="tb-footer-inner">');
  out.push('    <a class="tb-footer-brand" href="/" aria-label="TeeBox home"><span class="tb-footer-logo"><span>Tee</span>Box</span></a>');
  out.push('    <div class="tb-footer-links" role="navigation" aria-label="Footer">');
  for (const [label, href] of LINKS) out.push(`      <a href="${href}">${label}</a>`);
  out.push('    </div>');
  out.push('    <div class="tb-footer-apps">');
  out.push(`      <a class="tb-footer-badge" href="${APP_STORE_URL}" target="_blank" rel="noopener noreferrer"><img src="/assets/app-store-badge.svg" alt="Download on the App Store" width="120" height="40" loading="lazy" decoding="async"></a>`);
  out.push(`      <a class="tb-footer-social" href="${INSTAGRAM_URL}" target="_blank" rel="noopener noreferrer" aria-label="TeeBox on Instagram">${INSTAGRAM_SVG}</a>`);
  out.push('    </div>');
  out.push('  </div>');
  for (const row of extras) {
    out.push('  <div class="tb-footer-extra">');
    out.push(`    <span class="tb-footer-extra-label">${row.label}</span>`);
    for (const [label, href] of row.links) out.push(`    <a href="${href}">${label}</a>`);
    out.push('  </div>');
  }
  if (note) out.push(`  <p class="tb-footer-note" data-tb-note>${escapeHtml(note)}</p>`);
  out.push(`  <div class="tb-footer-legal"><span class="tb-footer-co">${LEGAL_CO}</span><span class="tb-footer-sep">·</span><span>${LEGAL_ADDR}</span></div>`);
  out.push('</footer>');
  out.push(END);
  return out.join('\n');
}

// ---------------------------------------------------------------------------
// Per-page transform
// ---------------------------------------------------------------------------
const FOOTER_RE = /[ \t]*<footer\b[\s\S]*?<\/footer>[ \t]*\r?\n?/g;
const REGION_RE = new RegExp(`[ \\t]*${START}[\\s\\S]*?${END}[ \\t]*\\r?\\n?`);
const BRAND_NOTE_RE = /(Independent golf marketplace, not affiliated with [^<]*?\.)/;

function detectNote(rel, oldFooter, existingRegion) {
  const cfg = PAGE_CONFIG[rel] || {};
  if (cfg.note) return cfg.note;
  // Preserve a note already stamped on a previous run.
  const kept = existingRegion && existingRegion.match(/<p class="tb-footer-note" data-tb-note>([\s\S]*?)<\/p>/);
  if (kept) return kept[1].replace(/&amp;/g, '&');
  // First run on a brand page: carry the disclaimer over from the old footer.
  const m = oldFooter && oldFooter.match(BRAND_NOTE_RE);
  return m ? m[1].replace(/\s+/g, ' ').replace(/&amp;/g, '&').trim() : '';
}

function processPage(rel) {
  const file = path.join(ROOT, rel);
  if (!fs.existsSync(file)) return { rel, status: 'missing' };
  const src = fs.readFileSync(file, 'utf8');
  const cfg = PAGE_CONFIG[rel] || {};
  let html = src;
  let status;

  const existing = html.match(REGION_RE);
  const footers = html.match(FOOTER_RE) || [];
  const strayFooters = existing ? footers.filter((f) => !existing[0].includes(f)) : footers;

  if (strayFooters.length > 1) {
    return { rel, status: 'SKIPPED', why: `${strayFooters.length} <footer> elements — refusing to guess` };
  }

  const region = renderFooter({
    extras: cfg.extras,
    note: detectNote(rel, strayFooters[0], existing && existing[0]),
    shim: cfg.shim,
    inline: cfg.inline,
  });

  if (existing) {
    // Re-run: swap the owned region. Drop a stray old <footer> if one crept back.
    html = html.replace(REGION_RE, (m) => {
      const indent = (m.match(/^[ \t]*/) || [''])[0];
      const trailing = /\r?\n$/.test(m) ? '\n' : '';
      return indent + region.split('\n').join('\n' + indent) + trailing;
    });
    if (strayFooters.length === 1) html = html.replace(strayFooters[0], () => '');
    status = 'unchanged';
  } else if (strayFooters.length === 1) {
    const old = strayFooters[0];
    const indent = (old.match(/^[ \t]*/) || [''])[0];
    const trailing = /\r?\n$/.test(old) ? '\n' : '';
    html = html.replace(old, () => indent + region.split('\n').join('\n' + indent) + trailing);
    status = 'replaced-existing';
  } else {
    const at = html.lastIndexOf('</body>');
    if (at === -1) return { rel, status: 'SKIPPED', why: 'no </body>' };
    html = html.slice(0, at) + region + '\n' + html.slice(at);
    status = 'inserted-new';
  }

  // Stylesheet in <head> (linked pages only).
  if (!cfg.inline && !html.includes(`href="${CSS_HREF}"`)) {
    const headClose = html.indexOf('</head>');
    if (headClose === -1) return { rel, status: 'SKIPPED', why: 'no </head>' };
    html = html.slice(0, headClose) + LINK_TAG + '\n' + html.slice(headClose);
  }

  if (html !== src) {
    if (status === 'unchanged') status = 'updated';
    if (!DRY && !CHECK) fs.writeFileSync(file, html);
  }
  return { rel, status };
}

// ---------------------------------------------------------------------------
const results = TARGETS.map(processPage);
const w = Math.max(...results.map((r) => r.rel.length));
console.log(`\nsync-footer${DRY ? ' (dry run)' : CHECK ? ' (check)' : ''}\n`);
console.log(`  ${'page'.padEnd(w)}  status`);
console.log(`  ${'-'.repeat(w)}  ${'-'.repeat(18)}`);
for (const r of results) console.log(`  ${r.rel.padEnd(w)}  ${r.status}${r.why ? `  (${r.why})` : ''}`);
const counts = results.reduce((a, r) => ((a[r.status] = (a[r.status] || 0) + 1), a), {});
console.log(`\n  ${Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(' · ')}\n`);

const stale = results.filter((r) => !['unchanged', 'missing'].includes(r.status) && !r.status.startsWith('SKIP'));
if (CHECK && stale.length) {
  console.error(`  ${stale.length} page(s) out of sync — run: node scripts/sync-footer.mjs`);
  process.exit(1);
}
if (results.some((r) => r.status === 'SKIPPED')) process.exitCode = 2;
