#!/usr/bin/env node
// Scan assets/logos/*.png and write a manifest of available slugs.
// dailySeed() filters the course pool by this set so the Bingo board
// only ever shows courses that have a real PNG logo — no emoji fallbacks.

import fs from 'node:fs';
import path from 'node:path';

const REPO_ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
// Derived from this script's own location — never a hardcoded clone path.
const ROOT = REPO_ROOT;
const LOGOS_DIR = path.join(ROOT, 'assets/logos');
const OUT = path.join(LOGOS_DIR, 'manifest.js');

const slugs = fs
  .readdirSync(LOGOS_DIR)
  .filter(f => f.endsWith('.png'))
  .map(f => f.replace(/\.png$/, ''))
  .sort();

// Passport-only logo set: /assets/logos/passport/{slug}.png. These are the
// ORIGINAL club marks (wordmarks intact) shown in Course Passport. A slug
// here is NOT added to the Bingo pool — Bingo only ever uses the wordless
// PNGs at the top level (LOGOS_AVAILABLE). Courses that exist only here
// (e.g. Sea Island, the TPCs) are Passport-selectable but never Bingo answers.
const PASSPORT_DIR = path.join(LOGOS_DIR, 'passport');
const passportSlugs = fs.existsSync(PASSPORT_DIR)
  ? fs.readdirSync(PASSPORT_DIR).filter(f => f.endsWith('.png')).map(f => f.replace(/\.png$/, '')).sort()
  : [];

const lines = [
  '// Auto-generated by scripts/generate-logos-manifest.mjs.',
  '// Lists course slugs with a real PNG logo in /assets/logos/.',
  '// dailySeed() filters Bingo course pool by this set — no emoji fallbacks.',
  '',
  'export const LOGOS_AVAILABLE = new Set([',
  ...slugs.map(s => `  '${s}',`),
  ']);',
  '',
  '// Slugs with an original (wordmark-intact) logo in /assets/logos/passport/.',
  '// Used by Course Passport only; never part of the Bingo pool.',
  'export const PASSPORT_LOGOS = new Set([',
  ...passportSlugs.map(s => `  '${s}',`),
  ']);',
  '',
];

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${slugs.length} bingo slugs + ${passportSlugs.length} passport slugs to ${OUT}`);
