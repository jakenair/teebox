#!/usr/bin/env node
// Scan assets/logos/*.png and write a manifest of available slugs.
// dailySeed() filters the course pool by this set so the Bingo board
// only ever shows courses that have a real PNG logo — no emoji fallbacks.

import fs from 'node:fs';
import path from 'node:path';

const REPO_ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
// Derived from this script's own location — never a hardcoded clone path.
const ROOT = REPO_ROOT;
const LOGOS_DIR = path.join(ROOT, 'assets/logos');
const OUT = path.join(LOGOS_DIR, 'manifest.js');

// Retired from the BINGO pool but still served. A logo cannot simply be
// deleted: dailyPuzzles docs are immutable for any date <= today (see
// writePuzzleForDate) and they embed the absolute logoUrl, so removing the
// file 404s a tile on a board people already played. Retiring keeps the file
// at its URL — old boards stay intact — while dropping it from
// LOGOS_AVAILABLE so no FUTURE board can draw it.
//
// royal-county-down (2026-09-30, founder call): the source art is clipped —
// the crest runs off the canvas and its side elements are cut mid-shape, and
// they are structurally attached to the crest so they cannot be cropped away.
// Re-padding in r293 improved the framing as far as that file allows. It
// stays in PASSPORT_LOGOS, where it renders larger and reads fine.
// the-golf-club (2026-10-05, founder call): the mark is a stag, crossed clubs
// and a ribbon that READS "The Golf Club" — the tile would spell its own
// answer. Connected-component analysis says there is nothing to crop to:
// stag, clubs, ribbon and lettering are a single blob, 95.2% of all ink, so
// unlike Hazeltine (whose golfer is a separate component and was extracted)
// the text cannot be removed without destroying the mark. Standing rule:
// never ship a Bingo tile that spells its own answer. Still served, so
// Passport keeps it.
const RETIRED_FROM_BINGO = new Set([
  'royal-county-down',
  'the-golf-club',
]);

const slugs = fs
  .readdirSync(LOGOS_DIR)
  .filter(f => f.endsWith('.png'))
  .filter(f => !RETIRED_FROM_BINGO.has(f.replace(/\.png$/, '')))
  .map(f => f.replace(/\.png$/, ''))
  .sort();

// Passport-only logo set: /assets/logos/passport/{slug}.png. These are the
// ORIGINAL club marks (wordmarks intact) shown in Course Passport. A slug
// here is NOT added to the Bingo pool — Bingo only ever uses the wordless
// PNGs at the top level (LOGOS_AVAILABLE). Courses that exist only here
// (e.g. Sea Island, the TPCs) are Passport-selectable but never Bingo answers.
const PASSPORT_DIR = path.join(LOGOS_DIR, 'passport');
const passportSlugs = fs.existsSync(PASSPORT_DIR)
  ? fs.readdirSync(PASSPORT_DIR).filter(f => f.endsWith('.png')).map(f => f.replace(/\.png$/, '')).sort()
  : [];

const lines = [
  '// Auto-generated by scripts/generate-logos-manifest.mjs.',
  '// Lists course slugs with a real PNG logo in /assets/logos/.',
  '// dailySeed() filters Bingo course pool by this set — no emoji fallbacks.',
  '',
  'export const LOGOS_AVAILABLE = new Set([',
  ...slugs.map(s => `  '${s}',`),
  ']);',
  '',
  '// Slugs with an original (wordmark-intact) logo in /assets/logos/passport/.',
  '// Used by Course Passport only; never part of the Bingo pool.',
  'export const PASSPORT_LOGOS = new Set([',
  ...passportSlugs.map(s => `  '${s}',`),
  ']);',
  '',
];

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${slugs.length} bingo slugs + ${passportSlugs.length} passport slugs to ${OUT}`);
